"""Printable PDF receipt, generated on demand from the stored records."""

from io import BytesIO

from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A5
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from apps.finance.templatetags.money import money

BRAND = colors.HexColor("#1a6b4d")


def render_receipt_pdf(receipt, site_name="DeptHub"):
    payment = receipt.payment
    department = payment.department
    payer = payment.payer_membership.user if payment.payer_membership else None
    profile = getattr(payer, "profile", None) if payer else None

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A5,
        leftMargin=14 * mm,
        rightMargin=14 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title=f"Receipt {receipt.receipt_number}",
        author=site_name,
    )
    styles = getSampleStyleSheet()
    styles["Title"].textColor = BRAND
    small = styles["Normal"].clone("small", fontSize=8, textColor=colors.HexColor("#475569"))

    story = [
        Paragraph(department.name, styles["Title"]),
        Paragraph("Official receipt", styles["Heading3"]),
        Spacer(1, 4 * mm),
    ]
    issued = timezone.localtime(receipt.issued_at)
    details = [
        ["Receipt number", receipt.receipt_number],
        ["Issued", issued.strftime("%d %b %Y, %H:%M")],
        ["Received from", profile.full_name if profile else (payer.email if payer else "—")],
        ["Student number", (profile.student_number if profile else None) or "—"],
        ["Method", payment.method_label],
        ["Reference", payment.provider_reference or payment.external_reference or "—"],
        ["Amount", money(payment.amount, payment.currency)],
    ]
    if receipt.receipt_status != receipt.Status.ISSUED:
        details.append(["Status", receipt.get_receipt_status_display().upper()])
    table = Table(details, colWidths=[38 * mm, None], hAlign="LEFT")
    table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LINEBELOW", (0, -1), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ]
        )
    )
    story += [table, Spacer(1, 5 * mm), Paragraph("Applied to", styles["Heading4"])]

    rows = [["Dues", "Session", "Amount"]]
    for allocation in payment.allocations.select_related(
        "dues_assessment__dues_type", "dues_assessment__department_membership__academic_session"
    ):
        a = allocation.dues_assessment
        rows.append(
            [
                Paragraph(a.dues_type.name, styles["Normal"]),
                a.department_membership.academic_session.name,
                money(allocation.amount_allocated, payment.currency),
            ]
        )
    if len(rows) == 1:
        rows.append(["Not yet applied to any dues", "", ""])
    applied = Table(rows, colWidths=[None, 24 * mm, 28 * mm])
    applied.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ALIGN", (2, 0), (2, -1), "RIGHT"),
                ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    story += [
        applied,
        Spacer(1, 8 * mm),
        Paragraph(
            f"Generated by {site_name} from the department's payment records. "
            "Verify a receipt by its number with the department's financial officers.",
            small,
        ),
    ]
    doc.build(story)
    return buffer.getvalue()
